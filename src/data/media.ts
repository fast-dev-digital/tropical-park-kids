export type MediaType = 'image' | 'video'
export type MediaOrientation = 'portrait' | 'landscape' | 'square'
export type MediaPriority = 'star' | 'featured' | 'support'
export type GalleryFilter = 'destaques' | 'centopeia' | 'chacara' | 'buffet' | 'decoracao' | 'quadra'
export type SectionTag =
  | 'hero'
  | 'attractions'
  | 'differentials'
  | 'structure'
  | 'events'
  | 'menus'
  | 'trust'
  | 'location'

export type MediaAsset = {
  id: string
  type: MediaType
  src: string
  poster?: string
  alt: string
  caption: string
  priority: MediaPriority
  orientation: MediaOrientation
  sectionTags: SectionTag[]
  objectPosition?: string
}

const photo = (
  id: string,
  file: string,
  alt: string,
  caption: string,
  orientation: MediaOrientation,
  sectionTags: SectionTag[],
  priority: MediaPriority = 'support',
  objectPosition = 'center',
): MediaAsset => ({
  id,
  type: 'image',
  src: `/gallery/photos/${file}`,
  alt,
  caption,
  priority,
  orientation,
  sectionTags,
  objectPosition,
})

const video = (
  id: string,
  file: string,
  alt: string,
  caption: string,
  orientation: MediaOrientation,
  sectionTags: SectionTag[],
  priority: MediaPriority = 'support',
  objectPosition = 'center',
): MediaAsset => ({
  id,
  type: 'video',
  src: `/gallery/optimized/${file}-optimized.mp4`,
  poster: `/gallery/posters/${file}-poster.webp`,
  alt,
  caption,
  priority,
  orientation,
  sectionTags,
  objectPosition,
})

